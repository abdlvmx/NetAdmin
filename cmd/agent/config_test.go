package main

import (
	"os"
	"path/filepath"
	"testing"
)

// Файл настроек, который есть, но не читается, не должен выглядеть как
// отсутствующий.
//
// Каталог установки закрыт для всех, кроме SYSTEM и администраторов, поэтому
// проверка, запущенная обычным пользователем, настроек не прочитает. Если
// счесть их незаданными, agent -check скажет «адрес сервера не задан» про
// исправно работающего агента и отправит переустанавливать его — диагноз,
// обратный действительности.
//
// Нехватку прав тест изобразить не может: отобрать доступ у самого себя не
// выходит. Проверяется то же различие на нечитаемом по другой причине пути —
// важно, что ошибка чтения не выдаётся за отсутствие файла.
func TestUnreadableConfigIsNotMistakenForMissing(t *testing.T) {
	dir := t.TempDir()
	if err := os.Mkdir(filepath.Join(dir, "agent_config.json"), 0o755); err != nil {
		t.Fatal(err)
	}

	if _, err := readAgentConfig(dir); err == nil {
		t.Fatal("нечитаемый файл настроек прочитался без ошибки — " +
			"проверка спутает нехватку прав с незаданными настройками")
	}
}

// Отсутствие файла ошибкой не считается: настройки могут прийти из окружения,
// и агент без файла — обычное дело для установки через install_agent.bat.
func TestMissingConfigIsNotAnError(t *testing.T) {
	c, err := readAgentConfig(t.TempDir())
	if err != nil {
		t.Fatalf("отсутствие файла настроек не ошибка, получено: %v", err)
	}
	if c.ServerURL != "" {
		t.Errorf("пустой каталог дал адрес %q", c.ServerURL)
	}
}
