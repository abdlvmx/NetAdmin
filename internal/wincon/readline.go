package wincon

import "os"

// readLine читает одну строку прямо из os.Stdin, без буферизации.
//
// Буферизованный чтец здесь не годится: он забирает из потока всё, что уже
// доступно, а лишнее оставляет в своём буфере. Для диалога, где вопросы
// задаются один за другим, это означает потерю ответов — второй вопрос
// получает EOF, потому что его строку прочитал и выбросил первый. В живой
// консоли это незаметно (человек печатает медленнее, чем идут вопросы), а при
// вставке нескольких строк сразу или подаче ввода из файла ломается.
//
// Второе значение — false, если строки не будет: поток закончился, и
// вызывающий не должен принять это за пустой ответ.
func readLine() (string, bool) {
	var (
		buf  [1]byte
		out  []byte
		read bool
	)
	for {
		n, err := os.Stdin.Read(buf[:])
		if n > 0 {
			read = true
			if buf[0] == '\n' {
				break
			}
			if buf[0] != '\r' { // перевод строки Windows приходит парой
				out = append(out, buf[0])
			}
		}
		if err != nil {
			break
		}
	}
	return string(out), read
}
