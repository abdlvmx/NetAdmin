// Package version — версия продукта.
//
// Одна на оба бинарника. Сервер и агент собираются из одного дерева и уезжают
// одним релизом; два независимых номера означали бы только лишний вопрос —
// какой из них настоящий. До появления пакета номер был лишь у агента, а на
// вопрос «какая у вас версия сервера» ответить было нечем: ни флага, ни строки
// в интерфейсе.
package version

import (
	"runtime/debug"
	"time"
)

// Value — номер версии. При сборке релиза подменяется номером тега:
//
//	go build -ldflags "-X netadmin/internal/version.Value=1.2.0" ./cmd/netadmin
//
// Так это делает .github/workflows/release.yml; совпадение имени символа с
// тем, что записано в рабочем процессе, держит TestReleaseStampsVersion.
//
// Значение по умолчанию уезжает в сборки, собранные из исходников вручную:
// номер там по определению приблизительный, поэтому показывать его в одиночку
// нельзя — для этого есть Full.
var Value = "1.1.0"

// Build — из чего собран этот бинарник.
type Build struct {
	Revision string    // ревизия git
	Time     time.Time // время ревизии
	Modified bool      // дерево на момент сборки было с правками
}

// Short — ревизия в коротком виде, как её показывает git log --oneline.
func (b Build) Short() string {
	if len(b.Revision) > 7 {
		return b.Revision[:7]
	}
	return b.Revision
}

// Self — сведения о сборке, которые Go кладёт в бинарник сам.
//
// Те же две строки читает internal/agentbin — но там их берут из *чужого*
// файла, чтобы сравнить сборку встроенного агента с сервером. Здесь речь о
// своей, и тянуть ради этого зависимость на agentbin незачем: пакет версии
// должен оставаться листом.
func Self() (Build, bool) {
	bi, ok := debug.ReadBuildInfo()
	if !ok {
		return Build{}, false
	}
	var b Build
	for _, s := range bi.Settings {
		switch s.Key {
		case "vcs.revision":
			b.Revision = s.Value
		case "vcs.time":
			b.Time, _ = time.Parse(time.RFC3339, s.Value)
		case "vcs.modified":
			b.Modified = s.Value == "true"
		}
	}
	return b, b.Revision != ""
}

// Full — версия для показа человеку и для ответа на вопрос «какая у вас
// версия» в сообщении об ошибке.
//
// К номеру добавляется ревизия git: номер отвечает, какого поколения продукт,
// ревизия — какая именно это сборка. Без второго вопрос остаётся наполовину
// открытым, потому что между тегами версия не меняется, а код меняется.
// Отметка «с правками» — про сборку из дерева, где были несохранённые
// изменения: такая сборка не воспроизводится по ревизии, и знать об этом
// важнее, чем выглядеть аккуратно.
func Full() string {
	b, ok := Self()
	return format(Value, b, ok)
}

// format вынесена отдельно, чтобы её проверял тест: сведения о сборке самого
// тестового бинарника подставить нельзя — та же причина, что у
// agentbin.compare.
func format(value string, b Build, ok bool) string {
	if !ok {
		return value // сборка не из репозитория: добавить к номеру нечего
	}
	s := value + " · " + b.Short()
	if b.Modified {
		s += " (с правками)"
	}
	return s
}
