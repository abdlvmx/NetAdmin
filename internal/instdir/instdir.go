// Package instdir — постоянный каталог установки и права на него.
//
// Сервер и агент ставятся в один каталог: агент обслуживает в том числе машину
// сервера, а два каталога значили бы два места, где искать настройки, журналы и
// состояние.
//
// Права на этот каталог — не косметика. В нём лежат база с хешами паролей и
// токенами агентов, config.json с постоянным токеном и файл службы, которая
// работает от LocalSystem. Каталог, унаследовавший права C:\ProgramData, даёт
// обычному пользователю право положить туда файл, а созданному — полный доступ
// к нему; отсюда до подмены файла службы и полных прав на машине один шаг.
//
// Режим файла в os.WriteFile тут не помогает: на Windows Go отображает его
// только в атрибут «только чтение» и списка доступа не ставит. Права файл
// получает по наследству от каталога — поэтому защита ровно одна, и она здесь.
package instdir

import (
	"errors"
	"os"
	"path/filepath"
)

// ErrUnsupported возвращается вне Windows: каталог установки существует только
// там, где есть служба (см. internal/winsvc).
var ErrUnsupported = errors.New("каталог установки существует только в Windows")

// Path — постоянный каталог установки.
func Path() string {
	base := os.Getenv("ProgramData")
	if base == "" {
		base = `C:\ProgramData`
	}
	return filepath.Join(base, "NetAdmin")
}
